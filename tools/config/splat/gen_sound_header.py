#!/usr/bin/env python3
"""Generate the C constants of a declared sound bank's named sounds.

    gen_sound_header.py NAME OUTPUT     the sound bank NAME's `sounds`, as `<PREFIX>_SOUND_<SOUND> = entry`

The entries are the bank's own (its script indices, what `SOUND_CHARACTER`, `SOUND_AREA` and `SOUND_WEAPON` take
beside the bank). The prefix is the bank's group and its own name less `sounds`: a group's `sounds` takes the group's
name (enemies/stranger/sounds: STRANGER_SOUND_WALK_STEP_A), `sounds_<x>` and `<x>_sounds` add x
(stages/akropolis/actors/helicopter_landing_pad_no_9/sounds: NO_9_AKROPOLIS_SOUND_FIRE, pe/antibody/level1_sounds: ANTIBODY_LEVEL1_SOUND_..),
and where two banks would still share a prefix, both take one more level of their groups
(enemies/golem/pawn/beam_sword/sounds_set_1: PAWN_BEAM_SWORD_SET_1_SOUND_..).
"""
from __future__ import annotations

import argparse
import functools
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "peassets"))

import asset_data  # noqa: E402


def _stem(name: str, depth: int) -> str:
    parts = name.split("/")
    group, local = parts[:-1], parts[-1]
    own = local.removeprefix("sounds_").removesuffix("_sounds") if local != "sounds" else ""
    return "_".join(group[-depth:] + ([own] if own else []))


def prefixes(assets: dict) -> dict[str, str]:
    """{bank: the prefix of its constants}: the bank's group and own name, taking more of the group until no two banks'
    prefixes clash - so a rename can change other banks' prefixes too."""
    banks = sorted(k for k, r in assets.items() if r.get("type") == "sound_bank")
    depth = {b: 1 for b in banks}
    while True:
        seen: dict[str, list[str]] = {}
        for b in banks:
            seen.setdefault(_stem(b, depth[b]), []).append(b)
        clashes = [bs for bs in seen.values() if len(bs) > 1]
        if not clashes:
            return {b: _stem(b, depth[b]).upper() + "_SOUND_" for b in banks}
        for bs in clashes:
            for b in bs:
                depth[b] += 1


@functools.lru_cache(maxsize=None)
def _prefixes() -> dict[str, str]:
    return prefixes(asset_data.ASSETS)


def prefix(name: str) -> str:
    return _prefixes()[name]


def header_source(name: str) -> str:
    sounds = asset_data.ASSETS[name].get("sounds") or {}
    guard = "ASSETS_" + name.upper().replace("/", "_") + "_H"
    rows = [f"    {prefix(name)}{sound.upper()} = {entry},"
            for sound, entry in sorted(sounds.items(), key=lambda kv: (kv[1], kv[0]))]
    return ("/* Generated by tools/config/splat/gen_sound_header.py from the sound bank " + name + ".\n"
            "   Do not edit: change the assets and rebuild. */\n\n"
            f"#ifndef {guard}\n#define {guard}\n\n/// The named sounds of {name}, by their entry in the bank.\n"
            "enum {\n" + "\n".join(rows) + f"\n}};\n\n#endif // {guard}\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", help="the sound bank's name")
    ap.add_argument("output", type=Path)
    args = ap.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header_source(args.name))


if __name__ == "__main__":
    main()
