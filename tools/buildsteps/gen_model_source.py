#!/usr/bin/env python3
"""Generate a declared model's whole C definition: its arrays and its `TmdSource` record.

A declared model (asset type `model`) is built from its USD and its binding, never from the package: the model is
encoded (tools/peassets/model/declared.py), cut by the layout the encoder writes - skeleton, part vertex counts,
vertices, normals, stream, record - and written as one include. The record is named by the model's `symbol`, static
when the name starts with an underscore (the project's TU-local names: every source carrying the model defines its own
copy); its arrays take that name as their prefix. Everything in the record is derived from the model.

    gen_model_source.py NAME OUTPUT [--assets assets/USA]

Undeclared models (`tmd`) keep their five per-array includes from gen_model_inc.py.
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "peassets"))

import asset_data  # noqa: E402
import asset_schema  # noqa: E402
from model import codec, declared  # noqa: E402

def array(declaration: str, count: int, rows: list[str], comment: str = "") -> str:
    """`declaration[count] = { rows }` (a row may hold several elements); an empty pool is a GNU zero-length array, which GCC places where the next
    array starts - where every retail record points for a pool its model does not have."""
    head = f"/* {comment} */\n" if comment else ""
    if not count:
        return f"{head}{declaration}[0] = {{}};\n"
    return f"{head}{declaration}[{count}] = {{\n" + "\n".join(rows) + "\n};\n"


def svectors(rows) -> list[str]:
    return [f"    {{ {', '.join(map(str, v))} }}," for v in rows]


def words(values) -> list[str]:
    values = list(values)
    return ["    " + " ".join(f"0x{w:08X}," for w in values[i:i + 4]) for i in range(0, len(values), 4)]


def bones(rows) -> list[str]:
    return ["    { { { " + ", ".join("{ " + ", ".join(map(str, b[i:i + 3])) + " }" for i in (0, 3, 6))
            + " }, { " + ", ".join(map(str, b[9:12])) + f" }} }}, {b[12]} }}," for b in rows]


def source(name: str, assets_root: Path) -> str:
    assets, embedded = asset_data.ASSETS, asset_data.EMBEDDED_ASSETS
    blob = declared.encode(name, assets, embedded, assets_root)
    address = asset_schema.embedded_address(embedded[name])
    record = len(blob) - codec.RECORD_SIZE
    m = codec.decode_raw(blob, address, record)
    sym = assets[name].get("symbol")
    if not sym:
        raise SystemExit(f"{name}: a model built into C names its record (`symbol`)")
    # A record named with a leading underscore is the project's TU-local name: it is defined static, so each
    # source carrying the model defines its own copy. Its arrays are always the record's file-local helpers.
    storage = "static " if sym.startswith("_") else ""
    skeleton, counts, verts, normals, stream = (f"_{sym.lstrip('_')}{part}" for part in
                                                ("Skeleton", "PartVerts", "Verts", "Normals", "Stream"))
    stream_words = struct.unpack_from(f"<{(record - m['_at']['stream']) // 4}I", blob, m["_at"]["stream"])
    binding = declared.binding_of(name, assets)
    model_file = declared.source_path(name, assets, assets_root).relative_to(assets_root)
    # A stream-only source has no count table: its record holds NULL, not an empty pool.
    count_table = "" if m["counts"] is None else array(
        f"static u32 {counts}", len(m["counts"]), [f"    {n}," for n in m["counts"]]) + "\n"
    return f"""/* Generated by tools/buildsteps/gen_model_source.py from {model_file} and its binding {binding}.
   Do not edit: change the model and rebuild. */

#include "main/tmd_types.h"

{array(f"static TmdBone {skeleton}", len(m["bones"]), bones(m["bones"]))}
{count_table}{array(f"static SVECTOR {verts}", len(m["verts"]), svectors(m["verts"]))}
{array(f"static SVECTOR {normals}", len(m["normals"]), svectors(m["normals"]))}
{array(f"static u32 {stream}", len(stream_words), words(stream_words), "First model creation resolves the commands' draw-handler slots in place.")}
{storage}TmdSource {sym} = {{
    .handlersResolved    = {m['flag']},
    .bufferHalfBytes     = {m['bufferHalfBytes']},
    .preXformRegionBytes = {m['preXformRegionBytes']},
    .partCount           = {len(m['bones'])},
    .partVertexCounts    = {"NULL" if m["counts"] is None else counts},
    .verts               = {verts},
    .normals             = {normals},
    .skeleton            = {skeleton},
    .stream              = {stream},
}};
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", help="the declared model's asset name")
    ap.add_argument("output", type=Path)
    ap.add_argument("--assets", type=Path, default=ROOT / "assets" / "USA")
    args = ap.parse_args()
    text = source(args.name, args.assets)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)


if __name__ == "__main__":
    main()
