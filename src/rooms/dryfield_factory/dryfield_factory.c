/// Rebuilds four faces of the room's collision grid from a template, moved
/// into the frame of the task's model: the template normals are rotated into
/// grid normals 2..5 and its corners rotated and translated into corners 8..15.
/// When `remapFaces` is set, the template's four face records are copied into
/// faces 2..5 with their corner and normal indices rebased onto those slots.
static void func_dryfield_factory_8017E140(Task* task, s32 remapFaces, s32 useAltTemplate)
{
    long          flag;
    GfxCoord*     coord;
    MATRIX*       m;
    GpGridParams* geom;
    GpGridParams* src;
    SVECTOR*      s;
    SVECTOR*      d;
    GpGridFace*   sf;
    GpGridFace*   df;
    u16*          sv;
    u16*          dv;
    s32           i;
    s32           j;

    coord = task->extra.tmd->coords;
    if (gGameSession->location.loc.stage == 2) {
        geom = &D_dryfield_factory_80187BF8;
    } else {
        geom = &D_dryfield_night_factory_80187BF0;
    }
    if (useAltTemplate != 0) {
        src = &D_dryfield_factory_80186E04;
    } else {
        src = &D_dryfield_factory_80186D38;
    }

    m = &coord->coord;
    s = src->field_4;
    d = geom->field_4 + 2;
    for (i = 0; i < 4; i++) {
        gte_SetRotMatrix(m);
        gte_ldv0(s);
        s++;
        gte_rtv0();
        gte_stsv(d);
        d++;
    }

    gte_SetRotMatrix(m);
    gte_SetTransMatrix(m);
    s = src->field_8;
    d = geom->field_8 + 8;
    for (i = 0; i < 8; i++) {
        RotTransSV(s++, d++, &flag);
    }

    if (remapFaces != 0) {
        sf = src->field_C;
        df = geom->field_C + 2;
        for (i = 0; i < 4; i++) {
            j  = 0;
            dv = df->verts;
            sv = sf->verts;
            do {
                *dv++ = *sv++ + 8;
            } while (++j < 4);
            df->normalIndex  = sf->normalIndex + 2;
            df->surfaceClass = sf->surfaceClass;
            df++;
            sf++;
        }
    }
}

