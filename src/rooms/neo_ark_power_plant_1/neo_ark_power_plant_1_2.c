/// Projects the world-space point `arg0` through `gGfxViewCoord.workm` and, unless
/// the GTE flags the projection, queues four gouraud `POLY_G4` wedges filling a
/// disc around it, tinted at the centre and black at the rim. `arg1` is the
/// radius in world units, scaled by depth; `arg2` is the tint as three 4-bit
/// channels (red at bit 8, green at bit 4, blue at bit 0), with 8 added to each
/// on odd display frames so the glow flickers. The room draws its steam and
/// spark glows with it.
static void func_neo_ark_power_plant_1_8017E184(SVECTOR* arg0, s32 arg1, s32 arg2)
{
    RoomDraw13Scratch* block;
    POLY_G4*           prim;
    s32                ang;
    s32                t;
    s32                t2;
    s32                packed;
    s32                blend;
    s32                tr;
    s32                tg;
    u8                 r;
    u8                 g;
    u8                 b;

    block = SCRATCH_PUSH(RoomDraw13Scratch);
    gte_SetTransMatrix(&gGfxViewCoord.workm);
    gte_SetRotMatrix(&gGfxViewCoord.workm);
    gte_ldv0(arg0);
    gte_rtps();
    gte_stsxy(&block->sx);
    gte_stflg(&block->flag);
    if (block->flag >= 0) {
        gte_stszotz(&block->otz);
        arg1          = ((s16)arg1 * 64) / block->otz;
        ang           = 0;
        blend         = ((u8)gDisplayState.animFrame & 1) * 8;
        packed        = arg2 << 16;
        tr            = (packed >> 20) & 0xF0;
        tg            = (packed >> 16) & 0xF0;
        r             = blend | tr;
        g             = blend | tg;
        b             = blend | ((arg2 & 0xF) << 4);
        block->radius = arg1;
        do {
            prim           = (POLY_G4*)gGpuPrimCursor;
            gGpuPrimCursor = prim + 1;
            setPolyG4(prim);
            setRGB0(prim, 0, 0, 0);
            setRGB1(prim, 0, 0, 0);
            setRGB2(prim, r, g, b);
            setRGB3(prim, 0, 0, 0);
            prim->x0 = block->sx + ((block->radius * rsin(ang)) >> 12);
            t        = ang + 0x200;
            prim->y0 = block->sy + ((block->radius * rcos(ang)) >> 12);
            prim->x1 = block->sx + ((block->radius * rsin(t)) >> 12);
            prim->y1 = block->sy + ((block->radius * rcos(t)) >> 12);
            t2       = ang + 0x400;
            prim->x2 = block->sx;
            prim->y2 = block->sy;
            prim->x3 = block->sx + ((block->radius * rsin(t2)) >> 12);
            prim->y3 = block->sy + ((block->radius * rcos(t2)) >> 12);
            ang      = t2;
            addPrim(Gpu_OtEntryAtByteOffset(((((u32)block->otz << gDisplayState.otDepthShift) >> 2) & 0xFFC)),
                    prim);
            Gp_AddTpageShift((P_TAG*)prim, 1, block->otz);
        } while (ang < 0x1000);
    }
    SCRATCH_POP(RoomDraw13Scratch);
}

/// Sprite-suppression switch for two of the area's views: 0 shows command 1
/// of views 5 and 6 and 1 hides it, through `GpSprtCmd::field_4`; any other
/// value is ignored.
void func_neo_ark_power_plant_1_8017E524(s32 arg0)
{
    GpAreaKey* sess;
    GpSprtRec* rec;
    GpSprtCmd* view;
    s32        v;

    sess = &gGameSession->at4.loc;
    rec  = Gp_SprtTables[sess->stage - 1]->field_0[sess->area - 1];
    v    = arg0 & 0xFF;

    if (v == 0) {
        view            = rec[5].field_4;
        view[1].field_4 = 0;
        view            = rec[6].field_4;
        view[1].field_4 = 0;
        return;
    }
    if (v == 1) {
        view            = rec[5].field_4;
        view[1].field_4 = v;
        view            = rec[6].field_4;
        view[1].field_4 = v;
    }
}
