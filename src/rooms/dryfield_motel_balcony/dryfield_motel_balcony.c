/// The balcony's event gate. A request whose flag nibble already records the
/// event (a set nibble, or a clear one for a negative `flagId`) answers 1. One
/// whose prerequisite item has not been collected runs the request's CAP
/// command and answers 0. Otherwise the gate answers 2 and - unless the
/// message's `field_5` asks for a dry run - latches the message and the
/// request, writes the flag nibble and spawns the event task.
s32 func_dryfield_motel_balcony_8017D5E8(RoomEventReq* req, RoomEventMsg* msg)
{
    s32 flag;
    s32 id;
    s32 mode;
    s32 got;
    s32 ret;
    s32 neg;

    flag                              = req->flagId;
    D_dryfield_motel_balcony_8018672C = 0;
    neg                               = flag < 0;
    got                               = (s16)flag;
    if (neg) {
        flag = -flag;
        got  = GameFlag_GetNibble(flag) == 0;
    } else {
        got = GameFlag_GetNibble(got);
    }
    ret = 1;
    if (got == 0) {
        if (Gp_HasCollectedBit(req->itemId) != 0 || req->itemId == 0) {
            ret = 2;
            if (msg->field_5 == 0) {
                D_dryfield_motel_balcony_80186724 = *msg;
                D_dryfield_motel_balcony_80186730 = *req;
                id                                = req->flagId;
                mode                              = 1;
                if (id < 0) {
                    id   = -id;
                    mode = 0;
                }
                GameFlag_SetNibble(id, mode);
                Task_SpawnFromTable(&D_dryfield_motel_balcony_80182270, 0, 0, 0);
                D_dryfield_motel_balcony_8018672C = 1;
                return 2;
            }
            return ret;
        }
        ret = 0;
        if (msg->field_5 == 0) {
            Gp_RunCapCmd1(req->field_4);
            Gp_SetNibbleIf(msg->field_6, 2);
            ret = 0;
        }
        return ret;
    }
    return ret;
}

/// The event task the gate spawns. It raises `Gp_StateF0.field_4`, runs the latched
/// request's CAP command, plays its two stage sounds in turn (either may be
/// absent) waiting for each voice to finish, then stores the latched
/// message's `msgId`, `field_2` and `field_3` as the save location's area,
/// warp and room, spawns task 0x11 and kills itself.
void func_dryfield_motel_balcony_8017D74C(Task* task)
{
    switch (task->state) {
        case 0:
            Gp_StateF0.field_4 = 1;
            Gp_MsgPlayerWeapon(0);
            Gp_RunCapCmd1(D_dryfield_motel_balcony_80186730.field_0);
            if (D_dryfield_motel_balcony_80186730.field_8 != 0) {
                SndEvt_EnqueueType6(D_dryfield_motel_balcony_80186730.field_8, 0, 0);
                task->state++;
            } else {
                task->state = 2;
            }
            break;
        case 1:
            if (SndVoice_HasActiveId(D_dryfield_motel_balcony_80186730.field_8) == 0) {
                task->state++;
            }
            break;
        case 2:
            task->state++;
            break;
        case 3:
            if (D_dryfield_motel_balcony_80186730.field_C != 0) {
                SndEvt_EnqueueType6(D_dryfield_motel_balcony_80186730.field_C, 0, 0);
                task->state++;
            } else {
                task->state = 5;
            }
            break;
        case 4:
            if (SndVoice_HasActiveId(D_dryfield_motel_balcony_80186730.field_C) == 0) {
                task->state++;
            }
            break;
        case 5:
            SndEvt_EnqueueType7(0x80000000, 0);
            gDisplayState.roomVariant = 1;
            Mc_SaveData.at4.loc.area  = D_dryfield_motel_balcony_80186724.msgId;
            Mc_SaveData.at4.loc.warp  = D_dryfield_motel_balcony_80186724.field_2;
            Mc_SaveData.at4.loc.room  = (u8)D_dryfield_motel_balcony_80186724.field_3;
            Task_Spawn(0, 0x11, 0, 0);
            taskKill(task);
            break;
    }
}

/// The room's message handler. It copies `msg` to `out`, filling `field_3`
/// from game flags for messages 0x1C, 0xF and 0x1F, then routes messages 0x1C,
/// 0x1F and 0x1E through the event gate with each one's request; when the
/// gate fires, it updates the collected and seen item bits (and, for 0x1E, a
/// flag nibble and `D_8007272D`). Any other message answers 1; a gate result
/// of 0 is reported as 2.
s32 func_dryfield_motel_balcony_8017D8BC(Task* task, s32 msgId, RoomEventMsg* msg, RoomEventMsg* out)
{
    RoomEventReq req;
    s32          flagClear;
    s32          ret;

    *out = *msg;
    if (msg->msgId == 0x1C && msg->field_5 == 0) {
        out->field_3 = GameFlag_GetNibble(0x61) + 1;
    }
    if (msg->msgId == 0xF && msg->field_5 == 0) {
        out->field_3 = GameFlag_GetNibble(0x61) + 1;
    }
    if (msg->msgId == 0x1F && msg->field_5 == 0) {
        flagClear    = GameFlag_GetNibble(0x96) == 0;
        out->field_3 = flagClear ? 1 : 2;
    }
    if (msg->msgId == 0x1C) {
        req.field_0 = 7;
        req.field_4 = 4;
        req.field_8 = Gp_PackStageSndId(0x521D000A);
        req.field_C = Gp_PackStageSndId(0x521D0001);
        req.flagId  = 0x43;
        req.itemId  = 0x13;
        ret         = func_dryfield_motel_balcony_8017D5E8(&req, out);
        if (D_dryfield_motel_balcony_8018672C != 0) {
            Gp_ClearCollectedBit(0x10F);
            Gp_ClearCollectedBit(0x112);
            Gp_SetItemSeenBit(0x113, 1);
        }
    } else if (msg->msgId == 0x1F) {
        req.field_0 = 5;
        req.field_4 = 2;
        req.field_8 = Gp_PackStageSndId(0x521D000A);
        req.field_C = Gp_PackStageSndId(0x521D0001);
        req.flagId  = 0x44;
        req.itemId  = 0x13;
        ret         = func_dryfield_motel_balcony_8017D5E8(&req, out);
        if (D_dryfield_motel_balcony_8018672C != 0) {
            Gp_ClearCollectedBit(0x10F);
            Gp_ClearCollectedBit(0x112);
            Gp_SetItemSeenBit(0x113, 1);
        }
    } else if (msg->msgId == 0x1E) {
        req.field_0 = 6;
        req.field_4 = 3;
        req.field_8 = Gp_PackStageSndId(0x521D000A);
        req.field_C = Gp_PackStageSndId(0x521D0001);
        req.flagId  = 0x2E;
        req.itemId  = 0xF;
        ret         = func_dryfield_motel_balcony_8017D5E8(&req, out);
        if (D_dryfield_motel_balcony_8018672C != 0) {
            GameFlag_SetNibble(0x30, 1);
            Mc_SaveData.sceneEvent = 3;
            func_800E3FAC(0xA2, 0xC);
        }
    } else {
        return 1;
    }
    if (ret == 0) {
        ret = 2;
    }
    return ret;
}

